import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
const skillPath = resolve('agent/skills/engineering-harness/SKILL.md');
const policyPath = resolve('agent/AGENTS.md');
const policy = readFileSync(policyPath, 'utf8');
const skill = readFileSync(skillPath, 'utf8');
const readme = readFileSync(resolve('README.md'), 'utf8');
const compact = (text: string) => text.toLowerCase().replace(/\s+/g, ' ');
test('shared skill names the canonical shared policy and host-aware loading', () => {
  const link = skill.match(/`([^`]*AGENTS\.md)` relative to this `SKILL\.md`/i);
  assert.ok(link, 'skill must identify the shared policy relative to its own source');
  assert.equal(resolve(dirname(skillPath), link[1]), policyPath);
  assert.match(compact(skill), /copilot cli/);
  assert.match(compact(skill), /missing or stale(?: from)? context/);
  assert.match(compact(skill), /reuse already injected context/);
  assert.match(compact(skill), /same source rather than a copy/);
  assert.match(compact(skill), /actual installed shared source/);
  assert.match(compact(skill), /pi-home examples apply only to pi/);
});
test('shared policy preserves Pi controls and fails closed only at affected capability', () => {
  const text = compact(policy);
  assert.match(text, /copilot cli/);
  assert.match(text, /missing required capability blocks only the affected workflow step, not unrelated work/);
  assert.match(text, /runtime-reported native custom-agent\/task dispatch and question tools when available/);
  assert.match(text, /never impersonate built-ins, substitute named roles, invent json schemas\/job apis, or prompt-emulate pi-only controls/);
  assert.match(text, /pi's actual named `subagent` calls, tools, control and model registry remain pi-native/);
  assert.match(text, /copilot uses the github cli-selected model/);
  assert.match(text, /`pi\.\*` and `roles\.json` are pi-only/);
  assert.match(text, /preserve user work, candidate\/worktree boundaries, security and project invariants/);
  assert.match(text, /readiness does not grant commit\/push\/merge\/publish\/deploy\/destructive-operation authority/);
  const preview = compact(readme.slice(readme.indexOf("### Copilot CLI preview boundary"), readme.indexOf("## Installation")));
  assert.match(preview, /all 20 canonical agents and six shared skills/);
  assert.match(preview, /one `backend-worker` read-only delegation/);
  assert.match(preview, /choice\/freeform questions/);
  assert.match(preview, /not a pinned minimum or sdk-loader compatibility claim/);
  assert.match(preview, /`unknown field ignored: metadata` warning/);
  assert.match(preview, /not an automatic copilot-global policy/);
  assert.match(preview, /pi extensions, patches and `settings\.example` remain pi-specific/);
  assert.match(preview, /`agent\/roles\.json` is the shared registry/);
  assert.match(preview, /observed cli was copilot v1\.0\.97/);
  assert.match(preview, /shared prompt files are not exported to copilot/);
  assert.match(preview, /not pi job\/grant\/control parity/);
  assert.match(preview, /pi's `\/learn` export is unchanged/);
  assert.match(preview, /does not establish execution of every role or skill/);
  assert.match(preview, /not verified installation steps/);
  assert.match(preview, /preview with the tested local `copilot --plugin-dir \.` path/);
  assert.match(preview, /marketplace install commands are unpublished-preview instructions/);
  assert.match(preview, /no authentication, global activation, commit, push, merge or release was performed/);
});
test('shared policy retains role list without substituting host identities', () => {
  const routing = compact(policy.slice(policy.indexOf('## Routing'), policy.indexOf('## Ownership')));
  assert.match(routing, /backend-worker for backend/);
  assert.match(routing, /database-worker for all database implementation/);
  assert.match(routing, /frontend-worker for all frontend ui/);
  assert.match(routing, /platform-worker for accepted terraform/);
  assert.match(routing, /general-worker for tooling, cli/);
  assert.match(routing, /debugger for debug/);
  assert.match(routing, /test-engineer for independent verify/);
  assert.match(routing, /reviewer for review/);
  assert.match(routing, /main never impersonates a selected role/);
});
